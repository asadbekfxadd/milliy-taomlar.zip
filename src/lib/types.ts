export type Size = { label: string; w: string; p: number };
export type Extra = { label: string; p: number };
export type Dish = {
  id: string;
  cat: string;
  name: string;
  ru: string;
  desc: string;
  ingr: string[];
  allergens: string[];
  weight: string;
  price: number;
  tags: string[];
  art: string;
  photo: string;
  sizes: Size[];
  extras: Extra[];
  available: boolean;
  featured: boolean;
};
export type Cat = { id: string; name: string; ru: string };
export type Menu = { cats: Cat[]; dishes: Dish[] };
export type Zone = { name: string; fee: number; min: number };
export type Settings = {
  name: string;
  tagline: string;
  phone: string;
  address: string;
  city: string;
  hours: string;
  mapUrl: string;
  instagram: string;
  telegram: string;
  pickup: boolean;
  delivery: boolean;
  prepTime: string;
  minOrder: number;
  zones: Zone[];
  pay: { cash: boolean; card: boolean };
  story: string[];
  storyPhotos: string[];
  /* POS */
  tables: number;
  servicePct: number;
  autoAcceptOnline: boolean;
  printGuestChecks: boolean;
  catStations: Record<string, string>;
  paper: '80' | '58';
};
export type CartItem = { key: string; id: string; si: number; ex: number[]; qty: number };
export type KitchenState = 'queued' | 'cooking' | 'ready';
export type OrderItem = {
  id: string; name: string; mods: string; qty: number; unit: number; sum: number;
  note?: string; station?: string; sent?: boolean; ks?: KitchenState | null; at?: number;
};
export type OrderStatus = 'new' | 'accepted' | 'cooking' | 'ready' | 'done' | 'cancelled';
export type PublicOrder = {
  id: string;
  no: number;
  status: OrderStatus;
  type: 'pickup' | 'delivery';
  fee: number;
  items: OrderItem[];
  subtotal: number;
  total: number;
  createdAt: string;
};
export type AdminOrder = PublicOrder & {
  name: string;
  phone: string;
  address: string;
  zone: string;
  note: string;
  when: string;
  pay: string;
};
