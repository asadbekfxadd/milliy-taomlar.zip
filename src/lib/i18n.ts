/** Russian portion text ("1 шампур · ~180 г", "5 шт") → Uzbek ("1 shampur · ~180 g", "5 dona"). */
export function unitText(s: string, lang: Lang) {
  if (lang === 'ru' || !s) return s;
  const end = '(?![A-Za-zА-Яа-яЁё])';
  return s
    .replace(/около\s*/g, '~')
    .replace(/шампур(ов|а)?/g, 'shampur')
    .replace(new RegExp('(\\d)\\s*шт\\.?' + end, 'g'), '$1 dona')
    .replace(new RegExp('шт\\.?' + end, 'g'), 'dona')
    .replace(new RegExp('(\\d)\\s*мл' + end, 'g'), '$1 ml')
    .replace(new RegExp('(\\d)\\s*кг' + end, 'g'), '$1 kg')
    .replace(new RegExp('(\\d)\\s*г' + end, 'g'), '$1 g')
    .replace(new RegExp('(\\d)\\s*л' + end, 'g'), '$1 l')
    .replace(/порци(я|и|й)/g, 'porsiya');
}

