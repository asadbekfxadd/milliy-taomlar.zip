export const DICT: Record<Lang, Record<Key, string>> = { ru, uz };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export type T = (key: Key, vars?: Record<string, string | number>) => string;
export const makeT = (lang: Lang): T => (k, v) => translate(lang, k, v);

